"""# Agent-based Defense (Model III)

Agent 1 - Label-Consisteny Agent
"""

class LabelCheckAgent:
    def __init__(self, reference_model, prob_threshold=0.98):
        """
        reference_model : clean baseline model (RF from Model I)
        prob_threshold  : confidence threshold for flagging suspicious labels
        """
        self.model = reference_model
        self.prob_threshold = prob_threshold

    def detect_suspicious(self, X, y):
        """
        Detect samples where the reference model is very confident
        but disagrees with the given label.
        """
        X = np.array(X)
        y = np.array(y)

        probs = self.model.predict_proba(X)
        preds = np.argmax(probs, axis=1)
        max_probs = probs.max(axis=1)

        suspicious_idx = np.where(
            (preds != y) & (max_probs >= self.prob_threshold)
        )[0]

        return suspicious_idx

    def relabel(self, X, y):
        """
        Relabel suspicious samples using the reference model.
        Returns: defended labels + indices that were changed.
        """
        X = np.array(X)
        y_def = np.array(y).copy()

        suspicious_idx = self.detect_suspicious(X, y_def)
        if len(suspicious_idx) > 0:
            corrected = self.model.predict(X[suspicious_idx])
            y_def[suspicious_idx] = corrected

        return y_def, suspicious_idx

