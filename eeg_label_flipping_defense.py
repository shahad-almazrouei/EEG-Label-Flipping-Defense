    print(f"Recall:    {rec:.4f}") #How many actual positives were correctly predicted (best close to 1, worse close to 0)
    print(f"F1 Score:  {f1:.4f}") #Harmonic mean of precision and recall (best close to 1, worse close to 0)
    #print(f"ROC-AUC:   {roc:.4f}" if roc is not None else "ROC-AUC:   Not available for this model")
