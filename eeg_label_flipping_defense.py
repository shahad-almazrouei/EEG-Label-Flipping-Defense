"""Agent 2 – Centroid Curator Agent"""

#This agent checks distance to class centroid and removes far outliers
def centroid_curator_agent(X, y, contamination_rate=0.03):
    """
    Centroid-based curator:
    - Computes centroid for each class.
    - Measures distance of each point to its class centroid.
    - Removes top contamination_rate fraction with largest distances.
    Returns: X_clean, y_clean, distances
    """
    X = np.array(X)
    y = np.array(y)

    centroids = {}
    unique_labels = np.unique(y)

    for label in unique_labels:
        centroids[label] = X[y == label].mean(axis=0)  # mean vector per class

    distances = np.zeros(len(X))
    for i in range(len(X)):
        centroid = centroids[y[i]]
        distances[i] = np.linalg.norm(X[i] - centroid)

    threshold = np.percentile(distances, 100 - contamination_rate * 100)
    keep_mask = distances <= threshold

    print(f"Centroid-based Curator Agent removed {np.sum(~keep_mask)} suspicious samples.")

    return X[keep_mask], y[keep_mask], distances

