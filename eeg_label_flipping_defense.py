"""# Data Poisoning Attack (Model II) - Label Flipping

"""

def poison_labels(y, poison_rate=0.15, random_state=42):

    rng = np.random.RandomState(random_state) #for reproducible randomness

    y = np.array(y)
    y_poisoned = y.copy()

    n_samples = len(y)
    n_poison = int(np.floor(poison_rate * n_samples)) #nr of labels to flip

    #randomly choose which samples to poison
    all_indices = np.arange(n_samples)
    poison_idx = rng.choice(all_indices, size=n_poison, replace=False)

    classes = np.unique(y) #all possible emotion labels

    #flipping labels
    for idx in poison_idx:
        current_label = y[idx]
        #pick a diff. label
        possible_labels = [c for c in classes if c != current_label]
        new_label = rng.choice(possible_labels)
        y_poisoned[idx] = new_label

    return y_poisoned, poison_idx

